  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('Stock', 'Mutual Fund', 'Crypto', 'Gold', 'Real Estate', 'Bond', 'ETF', 'Other')),
  invested_amount NUMERIC NOT NULL,
  current_value NUMERIC NOT NULL,
  date DATE NOT NULL,
  notes TEXT,
  quantity NUMERIC,
  symbol VARCHAR(20),
  last_updated TIMESTAMPTZ,
  auto_refresh BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_investments_date ON investments(date DESC);
CREATE INDEX IF NOT EXISTS idx_investments_type ON investments(type);
CREATE INDEX IF NOT EXISTS idx_investments_user_id ON investments(user_id);
CREATE INDEX IF NOT EXISTS idx_investments_symbol ON investments(symbol) WHERE symbol IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_investments_auto_refresh ON investments(auto_refresh) WHERE auto_refresh = TRUE;

-- ================= financial_goals =================
CREATE TABLE IF NOT EXISTS financial_goals (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  target_amount NUMERIC NOT NULL,
