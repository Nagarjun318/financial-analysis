-- ================= service_history =================
CREATE TABLE IF NOT EXISTS service_history (
  id SERIAL PRIMARY KEY,
  service_id INTEGER NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL,
  service_date DATE NOT NULL,
  service_provider TEXT,
  cost NUMERIC,
  notes TEXT,
  odometer_reading INTEGER,
  work_performed TEXT,
  parts_replaced TEXT[],
  next_service_due DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_service_history_service_id ON service_history(service_id);
CREATE INDEX IF NOT EXISTS idx_service_history_user_id ON service_history(user_id);
CREATE INDEX IF NOT EXISTS idx_service_history_service_date ON service_history(service_date DESC);

CREATE OR REPLACE FUNCTION create_service_history_on_update()
RETURNS TRIGGER AS $$
BEGIN
  IF (OLD.last_service_date IS DISTINCT FROM NEW.last_service_date)
     OR (OLD.cost IS DISTINCT FROM NEW.cost) THEN
    INSERT INTO service_history (
      service_id, user_id, service_date, service_provider, cost, notes, next_service_due
    ) VALUES (
      OLD.id, OLD.user_id, OLD.last_service_date, OLD.service_provider, OLD.cost, OLD.notes, OLD.next_service_due
    );
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS service_update_history_trigger ON services;
CREATE TRIGGER service_update_history_trigger
  BEFORE UPDATE ON services
  FOR EACH ROW
  EXECUTE FUNCTION create_service_history_on_update();

CREATE OR REPLACE FUNCTION create_initial_service_history()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO service_history (
    service_id, user_id, service_date, service_provider, cost, notes, next_service_due
  ) VALUES (
    NEW.id, NEW.user_id, NEW.last_service_date, NEW.service_provider, NEW.cost, NEW.notes, NEW.next_service_due
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS service_insert_history_trigger ON services;
CREATE TRIGGER service_insert_history_trigger
  AFTER INSERT ON services
  FOR EACH ROW
  EXECUTE FUNCTION create_initial_service_history();

CREATE OR REPLACE FUNCTION get_service_statistics(p_service_id INTEGER)
RETURNS TABLE (
  total_services BIGINT,
  total_cost NUMERIC,
  average_cost NUMERIC,
  last_service_date DATE,
  average_interval_days INTEGER
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    COUNT(*)::BIGINT AS total_services,
    COALESCE(SUM(cost), 0) AS total_cost,
    COALESCE(AVG(cost), 0) AS average_cost,
    MAX(service_date) AS last_service_date,
    CASE
      WHEN COUNT(*) > 1 THEN
        CAST((MAX(service_date) - MIN(service_date)) / NULLIF(COUNT(*) - 1, 0) AS INTEGER)
      ELSE 0
    END AS average_interval_days
  FROM service_history
  WHERE service_id = p_service_id;
END;
$$ LANGUAGE plpgsql;

