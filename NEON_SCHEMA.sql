-- Ported from Supabase: transactions, assets, liabilities, investments,
-- financial_goals, services, service_history, groceries, shopping_list,
-- category_budget, user_uploads
-- Auth: Neon Auth (Managed Better Auth) via Data API
-- RLS uses auth.user_id() (TEXT sub claim). All user_id columns are TEXT.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Shared updated_at trigger
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ================= transactions =================
CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  date DATE NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  amount NUMERIC NOT NULL DEFAULT 0,
  category TEXT NOT NULL DEFAULT 'Other',
  ai_category TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_transactions_user_id ON transactions(user_id);
CREATE INDEX IF NOT EXISTS idx_transactions_date ON transactions(date DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_category ON transactions(category);

-- ================= assets =================
CREATE TABLE IF NOT EXISTS assets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IS NOT NULL AND length(trim(type)) > 0),
  current_value NUMERIC NOT NULL DEFAULT 0,
  last_updated DATE,
  created_on DATE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_assets_user_id ON assets(user_id);

-- ================= liabilities =================
CREATE TABLE IF NOT EXISTS liabilities (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'loan',
  principal NUMERIC NOT NULL DEFAULT 0,
  opening_principal NUMERIC,
  current_principal NUMERIC,
  interest_rate_annual NUMERIC NOT NULL DEFAULT 0,
  monthly_emi NUMERIC NOT NULL DEFAULT 0,
  extra_payment_monthly NUMERIC NOT NULL DEFAULT 0,
  start_date DATE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
COMMENT ON COLUMN liabilities.principal IS 'Original loan principal amount. Current balance is calculated from payment history.';
CREATE INDEX IF NOT EXISTS idx_liabilities_user_id ON liabilities(user_id);

-- ================= investments =================
